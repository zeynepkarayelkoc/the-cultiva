<h2>Antalyalı Noel Baba</h2>



<p>Artık bütün dünyanın bildiği Noel Baba ya da Santa Klaus, hiç şüphe yok ki, İskandinavya ülkelerindeki iyilik sever çocukların koruyucusu ve sevindiricisi olan Noel Baba efsanesi ile Myra’lı Aziz Nicholaos’ın kişiliklerinin birleştirilmesiyle, yarı dinî ve çok popüler bir tipin doğmasıyla oluşmuştur. Öte yandan Santa Klaus'un Anadolu'da yaşayan bir din adamı olan Aziz Nicholaos olduğu da düşünülmektedir. </p>



<div class="wp-block-image"><figure class="aligncenter is-resized"><img src="https://upload.wikimedia.org/wikipedia/commons/thumb/e/eb/St_Nicholas_Icon_Sinai_13th_century.jpg/800px-St_Nicholas_Icon_Sinai_13th_century.jpg" alt="" width="600"/><figcaption><a href="https://en.wikipedia.org/wiki/Saint_Catherine%27s_Monastery">Aziz Catherine Manastırı</a>&nbsp;,&nbsp;<br><a href="https://en.wikipedia.org/wiki/Sinai_Peninsula">Sina'dan</a>&nbsp;Aziz Nikolaos'un 13. yüzyıldan kalma bir tasviri</figcaption></figure></div>



<p>Antalya'nın Demre (Myra) ilçesinde Aziz Nicholas kilisesi bulunması ve bu azizin çocuklara hediyeler vererek onları koruyup kollaması onun Noel Baba ile özdeşleştirilmesine olanak sağlamıştır. Aziz Nicholas'ın bir piskopos olması sebebiyle kırmızı bir pelerin giymesi ise halk arasında anlatılan bir detaydır.  Hristiyanların noel zamanında şömine başlarına çorap asması ise Aziz Nicholas'ın ihtiyaç sahibi insanların evlerinin önünde bulunan ayakkabıların içine para atması ile özdeşleşerek zamanla şekil değişikliğine ve pazarlama stratejilerine dönüşerek çorap halini almıştır. </p>



<p>Noel Baba karakterinin kızak ve geyiklerle gezmesi ise kültürel bir aktarımın sonucu ortaya çıkmıştır demek yanlış olmayacaktır. Çünkü Aziz Nicholas'ın yaşadığı Myra bir Akdeniz kentidir ve kızakla gezmeyi sağlayacak kadar kar almamaktır. Öte yandan kuzey ülkelerindeki geleneklerde ise kızak ve geyikleri sıkça görmekteyiz. Aziz Nicholas'ın Hristiyan bir aziz olması ve ölüm tarihinin 6 Aralık olarak kabul edilmesi ise onun Noel bayramı ile yakından bir ilişki içine sokmuştur.</p>



<p>Bir başka anlatıda ise "Roma imparatoru Diocletian'ın Hıristiyanlara karşı başlattığı tutuklama harekatından kurtulamayan Saint Nicholas (Noel Baba), büyük imparator Konstantin zamanında özgürlüğüne kavuşarak, İznik Konsül'üne bağlanır. Ölümünden sonra&nbsp; ise Myra (Demre) yakınlarına gömülür.&nbsp; 11. yüzyılda,&nbsp; İtalyan denizciler, Myra'dan aldıkları kemiklerini,&nbsp; İtalya'da yeniden defnederler.&nbsp; Böylece Saint Nicholas'nın efsaneleri Avrupa'ya yayılır. Efsanelerin,&nbsp; kat ettikleri coğrafyaların farklı yorumları dikkate alınmadığında, ortak yanı&nbsp; Hıristiyanlık inancının sembollerinden biri yapılmış, yari kutsal kişinin serüvenidir..."</p>



<h2>Noel Nedir?</h2>



<p>Noel, her yıl 25 Aralık tarihinde İsa'nın doğumunun kutlandığı Hristiyan bayramıdır. Ayrıca Doğuş Bayramı, Kutsal Doğuş veya Milat Yortusu olarak da bilinir. 20. yüzyılın başlarından itibaren Noel, Hristiyan olmayanlar tarafından da kutlanan, dinî motiflerinden arınmış, hediye alışverişi etrafında yoğunlaşan bir bayram olarak da kutlanmaya başlamıştır. Bu seküler Noel versiyonunda mitolojik figür Noel Baba temel bir rol oynar.</p>



<p>Noel, her yıl dünyadaki Hristiyanların çoğunluğu tarafından 25 Aralık'ta kutlanır. Bazı ülkelerde kutlamalar 24 Aralık'ta Noel arifesiyle başlar ve 25 Aralık bitimine kadar devam eder. Ermeni Kilisesi gibi bazı Doğu Ortodoks Kiliseleri, Jülyen takviminde 25 Aralık'a denk gelen 6 Ocak'ı Noel olarak kutlarlar. Hristiyanların çoğunlukta olduğu bazı ülkelerde pratik olarak Noel tatili yılbaşı tatiliyle birleştirilir. Yani yılbaşı ile noel kutlaması tamamen farklı şeyler olmasına rağmen iç içe geçerek bir anlam boşalması yaşamıştır.</p>



