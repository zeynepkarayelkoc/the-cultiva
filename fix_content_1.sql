<h2>Yılbaşı Kutlamaları</h2>



<p>Kültürler arası etkileşim ne kadar farklı olsa da yılbaşı kutlamaları tamamen Hristiyan toplumlardan gelmemiştir. Türklerin yılbaşı bayramları Nevruz ve Hıdırellez'dir ve gelenek içinde de yeri çok önemlidir. Cumhuriyet döneminde takvimin değişmesi ile birlikte Nevruz ve Hıdırellez'in de tarihleri değişmiştir. Nevruz ve Hıdırellez takvimin birinci gününü işaret eder, 1 Ocak da öyle... Aslında ortada olan bir tarih değişikliğinden başka bir şey değildir. Buna ilaveten sosyo-kültürel dokudaki değişiklik, arkaik mitleri öldürmüştür hepsi bu... Eğer Türkler, geçmişte yılbaşı kutlamamış olsalardı, 31 Aralıktaki yılbaşı bu derece etkili bir gelenek oluşturarak, halk arasında yayılma gücü bulamayacaktı. (OĞUZ,2013)</p>



<h2>NOEL BABA VE COCA COLA </h2>



<p>Noel baba bir efsaneden ve noel zamanı anlatılan gece masallarından ibaretken nasıl oldu da sokaklarda noel baba kostümleriyle gezen kişilere dönüştü? Noel Baba'nın metalaşma hikayesi elbette bir pazarlama stratejisiyle gerçekleşiyor. Bu da her gün neredeyse tonlarca litre tüketilen Coca- Cola markası sayesinde oluyor... </p>



<p>Noel Baba'yı ilk çizen kişi &nbsp;Thomas Nast (1863). Bir karikatürist olan Nast Noel Baba'yı o kutsal hikayelerde ya da kilisenin anlatılanlarındaki gibi değil de daha çok dünyevi zevklere ait olarak çizmiştir. </p>



<p>1929 yılında Amerika'da dev bir kriz oldu. İnsanların değil işe gidip para kazanmak camı açacak enerjileri kalmamıştı. Bu durum tabii ki  patronların canını sıktı ve reklam sektörü devreye girdi. 1930 yılında Coca Cola sadece bir efsaneden ibaret hale gelmiş Noel Baba'yı tekrar gün yüzüne çıkarttı... </p>



<p>Coca Cola'nın yeni reklam ikonu Noel Baba'yı Haddon Sundblom adlı sanatçı resmederek tekrar popülerleşmesini sağlamıştır. Fakat bu durum ilerleyen süreçlerde ortaya birçok farklı iddianın çıkmasına neden olmuştur. Bunlardan en bilineni olan Noel babanın aslında yeşil ceketli olması ve coca cola şirketi onu kendi renkleriyle yani kırmızı olarak resmetmesi.... Her ne kadar Coca- Cola ile noel babanın kapitalist bir yapıya bürünmesi mantıklı olsa renklerin değiştirilme durumu tamamen bir şehir efsanesinden ibarettir... </p>



<p>Noel Baba'nın bugünkü kırmızı kıyafetli tonton bir dede olarak hafızalara kazanması 1930 yılından önce de vardı örneğin <a href="https://en.wikipedia.org/wiki/Rose_O%27Neill">Rose O'Neill'in&nbsp;</a><em><a href="https://en.wikipedia.org/wiki/Puck_(magazine)">Puck'ın</a></em>&nbsp;1903 sayısı için yaptığı illüstrasyonda Noel Baba kırmızı kıyafetleriyle görülür...</p>



