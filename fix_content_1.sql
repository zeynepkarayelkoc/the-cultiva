<p>Gustav Klimt ’in ‘Pallas Athena’ adlı eseri sanatçının antik medeniyetlere karşı duyduğu ilgiyi belli etmektedir. Bu resimdeki karakter olan Pallas, Antik Yunan mitolojisinden seçilmiş bir karakterdir. Pallas Athena, Yunan mitolojisinde zekâ, sanat, strateji, ilham ve barış tanrıçasıdır. Geleneksel olarak Athena’nın giysisi üzerinde Medusa’nın başı dikkat çekmektedir. Klimt bu sembolü abartılı bir şekilde betimlemiştir. Mitolojide Medusa, Gorgon yaratıklarından en çok üne sahip olanı ve en çok korku salanıdır. Efsaneye göre Medusa kurbanını gözüne bakarak öldürebilmektedir ancak Perseus onu öldürebilmeyi başarmıştır. Perseus’un başarısı, Athena tanrıçası sayesinde gerçekleşmiş, Athena Medusa’ya karşı kalkanını tutarak ayna etkisi oluşturmuş böylelikle Perseus Medusa’nın başını kesmiştir. O günden beri Athena giysisi üzerinde Medusa’nın resmini taşımaktadır. Tabloda Athena’nın arkasında karanlık içerisinde iki figür sezilmektedir. Sağında Harakles solunda ise Triton bulunmakta ve savaşmaktadırlar. Harakles Romalıların ‘Hercules’ adı ile andıkları, ezici güce sahip bir<br>tanrı iken, Triton ise denizin uğultu tanrısıdır. Gustav Klimt bu resimde Triton ve Herakles karakterlerini sanat devriminin alegorisini oluşturmak için kullanmıştır. Bu karakterler Klimt’in sanata getirdiği yenilikleri simgeler. Birçok toplumda sol kavramı olumsuzluk anlamına gelirken Athena’nın solunda Triton bulunmakta ve bir deniz canavarı olarak düşünülerek, dönemin Viyana’daki tutucu sanatçıları temsil etmektedir. Sağ tarafında bulunan Harakles’in ise dönemin yeni sanat akımı olan Art Nouveau’yu temsil eden sanatçıları temsil ettiği yorumlanıyor. Athena figürü ise karanlık karşısında gücün zaferi gibi bir duruş sergilemektedir. Asker giysisi taşıyan Athena, erkek karakterini çağrıştırmaktadır fakat silueti kadındır. Athena karakteri burada kadın olarak değil de maskülen kadın imgesi halinde androjen bir özellik yüklenmiştir.</p>



