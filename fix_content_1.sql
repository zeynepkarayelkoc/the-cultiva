<h2>Eski Türklerde Noel ve Ayaz Ata</h2>



<p><strong>Ayaz Ata</strong>&nbsp;Türk, Altay ve Orta Asya mitolojisinde yer alan&nbsp;soğuk tanrısıdır ve Noel Baba ile özdeşleşmiş durumdadır. Ayaz Ata ay&nbsp;ışığından yaratılmıştır. Soğuk havanın dünya üzerine gelmesini sağlar ve "Ak Ayas” olarak  da adı geçer. Ülker burcunun altı yıldızı göğün altı deliğidir ve oradan soğuk hava üfler ve kış gelir. Kazak kültüründe Noel Baba ile birebir şekilde özdeşleşmiştir. Kimi topluluklarda kışın ortaya çıkan ve insanlara yardım eden aziz bir kişi olarak da anılmaktadır. Hikayelere göre ona iyiliklerinde yardım ve eşlik eden bir kızı, bazı hikayelere göre de torunu vardır. Ona da “Ayaz Kız” yada “Kar Kızı” ismi verilmiştir.</p>



